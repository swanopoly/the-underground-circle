def slugify(name):
    return "-".join(part.lower() for part in name.split() if part)


def github_activity_block(circle):
    slug = circle.get("repo_slug") or slugify(circle["name"])
    members = circle["members"]
    m1 = members[0]["name"] if members else "a member"
    m2 = members[1]["name"] if len(members) > 1 else m1
    tasks = circle.get("tasks") or []
    if tasks:
        first_task_label = tasks[0].split("—")[0]
        first_task_label = re.sub(r"^\s*\[[^\]]*\]\s*", "", first_task_label).strip()
    else:
        first_task_label = "recent work"
    lines = [
        "## Recent GitHub Activity",
        f"Repo: {slug} (main branch)",
        f"- {m1} pushed 4 commits to {slug} today",
        f"- {m2} opened a PR: '{first_task_label}'",
        f"- CI passing on {slug}@main",
    ]
    return "\n".join(lines)


def integrations_block(circle):
    default = [
        "- GitHub: connected",
        "- Provider keys: default routing only (no BYOK provider connected)",
    ]
    lines = ["## Connected Integrations"] + circle.get("integrations", default)
    return "\n".join(lines)


def automations_block(circle):
    lines = [
        "## Automations",
        "- Daily check-in reminder posted at 9:00 AM circle time",
        "- Weekly XP leaderboard summary posted to Feed every Monday",
    ]
    return "\n".join(lines)


def grounding_block(model, source, refs):
    lines = [
        "## BlackSwan App-Grounding Contract",
        f"Runtime route: {model} (BlackSwan). Surface: {source}.",
        "Use Underground Circle app data, memory references, mission state, and tool outputs as the highest-priority facts.",
        "Do not invent app state. If a fact is not present in context or tool output, say what is missing or ask to look it up.",
        "Never expose secrets, API keys, vault values, or integration tokens. Mention only connection status and safe metadata.",
        "Memory/source references available this turn:",
    ]
    for ref in refs:
        score = f" score={ref['score']:.2f}" if "score" in ref else ""
        conf = f" confidence={ref['confidence']:.2f}" if "confidence" in ref else ""
        lines.append(f"- {ref['title']} [{ref['kind']} · {ref['scope']}{score}{conf}]")
    return "\n".join(lines)


def circle_info_block(circle):
    lines = [
        "## Circle Info",
        f"Name: {circle['name']}",
        f"Description: {circle['description']}",
        f"Members: {len(circle['members'])}",
        f"Checked in today: {circle['checked_in']}/{len(circle['members'])}",
    ]
    return "\n".join(lines)


def members_block(circle):
    lines = ["## Members"]
    for m in circle["members"]:
        lines.append(f"- {m['name']} ({m['role']}) — {m['streak']} day streak, longest: {m['longest']}")
    return "\n".join(lines)


def current_user_block(circle):
    u = circle["current_user"]
    lines = [
        "## Current User",
        f"Name: {u['name']}",
        f"Streak: {u['streak']} days",
        f"Longest streak: {u['longest']} days",
        f"Bio: {u['bio']}",
        f'XP: {u["xp"]} | Level {u["level"]} "{u["title"]}"',
        f"Grind Karma: {u['grind_karma']} | Social Karma: {u['social_karma']}",
    ]
    return "\n".join(lines)


def leaderboard_block(circle):
    lines = ["## XP Leaderboard"]
    for i, r in enumerate(circle["leaderboard"], start=1):
        lines.append(f"{i}. {r['name']} — {r['xp']} XP (Lv{r['level']})")
    return "\n".join(lines)


def goals_tasks_block(circle):
    lines = ["## Goals & Missions"]
    for g in circle["goals"]:
        lines.append(f"- {g}")
    lines.append("")
    lines.append("## Tasks (Kanban board)")
    for t in circle["tasks"]:
        lines.append(f"- {t}")
    return "\n".join(lines)


def activity_block(circle):
    lines = ["## Recent Activity Feed"]
    for a in circle["activity"]:
        lines.append(f"- {a}")
    return "\n".join(lines)


def with_auto_ref(circle, refs):
    auto = {
        "title": f"{circle['name']}: {circle['description']}",
        "kind": "app_state",
        "scope": "circle",
        "score": 0.7,
    }
    return list(refs) + [auto]


def build_system_prompt(circle, model, source, refs):
    refs = with_auto_ref(circle, refs)
    parts = [
        PERSONA,
        TOOLS_BLOCK,
        KNOWLEDGE_BLOCK,
        INSTRUCTIONS_BLOCK,
        SOUL_WISDOM_BLOCK,
        GUARDRAILS_BLOCK,
        SKILLS_LIBRARY_NOTE,
        grounding_block(model, source, refs),
        circle_info_block(circle),
        members_block(circle),
        current_user_block(circle),
        leaderboard_block(circle),
        goals_tasks_block(circle),
        activity_block(circle),
        github_activity_block(circle),
        integrations_block(circle),
        automations_block(circle),
    ]
    return "\n\n".join(parts)


def make_completion(think, answer):
    return f"<think>\n{think}\n</think>\n\n{answer}"


