#!/usr/bin/env node
/**
 * build-canonical-skills-seed — emit idempotent SQL that seeds every canonical
 * skill under skills/<name>/SKILL.md into a circle's `circle_skills` library.
 *
 * The SQL is safe to run in the Supabase SQL editor / psql: it dollar-quotes
 * the markdown bodies (no escaping needed), attributes each skill to the
 * circle's creator (`author_id = circles.created_by`), and uses
 * ON CONFLICT (circle_id, name) DO UPDATE so re-running refreshes content
 * rather than duplicating. Reversible with:
 *   DELETE FROM circle_skills WHERE circle_id = '<id>' AND name IN (...);
 *
 * Usage:
 *   node scripts/build-canonical-skills-seed.mjs --circle <circle-uuid> [> out.sql]
 *   node scripts/build-canonical-skills-seed.mjs            # emits a CIRCLE_ID placeholder
 */

import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillsDir = join(repoRoot, 'skills');

const circleArgIdx = process.argv.indexOf('--circle');
const circleId = (circleArgIdx >= 0 ? process.argv[circleArgIdx + 1] : '') || 'REPLACE_WITH_CIRCLE_UUID';

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
if (circleId !== 'REPLACE_WITH_CIRCLE_UUID' && !UUID_RE.test(circleId)) {
  console.error(`Refusing to emit: --circle "${circleId}" is not a full UUID.`);
  process.exit(1);
}

// Minimal frontmatter parse (mirrors src/lib/skillFrontmatter.ts); the
// canonical-skills smoke validates the files against the real parser.
function parseFrontmatter(content) {
  const m = content.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  const out = { name: '', description: '', version: '1.0.0', tags: [] };
  if (!m) return out;
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([a-zA-Z_][a-zA-Z0-9_]*):\s*(.+?)\s*$/);
    if (!kv) continue;
    const value = kv[2].replace(/^['"]|['"]$/g, '');
    if (kv[1] === 'name') out.name = value;
    else if (kv[1] === 'description') out.description = value;
    else if (kv[1] === 'version') out.version = value;
    else if (kv[1] === 'tags') {
      out.tags = value.replace(/^\[|\]$/g, '').split(',').map((s) => s.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);
    }
  }
  return out;
}

// Dollar-quote with a tag the content can't contain.
function dq(text) {
  let tag = 'uc';
  while (text.includes(`$${tag}$`)) tag += 'x';
  return `$${tag}$${text}$${tag}$`;
}
function sqlArray(tags) {
  if (!tags.length) return `'{}'::text[]`;
  return `ARRAY[${tags.map((t) => `'${t.replace(/'/g, "''")}'`).join(', ')}]::text[]`;
}

const skillNames = readdirSync(skillsDir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && existsSync(join(skillsDir, e.name, 'SKILL.md')))
  .map((e) => e.name)
  .sort();

const lines = [
  '-- Canonical-skill seed for circle_skills — generated by scripts/build-canonical-skills-seed.mjs',
  `-- Circle: ${circleId}`,
  '-- Idempotent: re-running refreshes content (ON CONFLICT (circle_id, name) DO UPDATE).',
  '-- Run in the Supabase SQL editor or psql.',
  '',
];
for (const name of skillNames) {
  const content = readFileSync(join(skillsDir, name, 'SKILL.md'), 'utf8');
  const fm = parseFrontmatter(content);
  lines.push(
    `INSERT INTO circle_skills (circle_id, author_id, name, description, version, tags, content)`,
    `VALUES (`,
    `  '${circleId}'::uuid,`,
    `  (SELECT created_by FROM circles WHERE id = '${circleId}'::uuid),`,
    `  '${fm.name.replace(/'/g, "''")}',`,
    `  ${dq(fm.description)},`,
    `  '${fm.version.replace(/'/g, "''")}',`,
    `  ${sqlArray(fm.tags)},`,
    `  ${dq(content)}`,
    `)`,
    `ON CONFLICT (circle_id, name) DO UPDATE SET`,
    `  description = EXCLUDED.description,`,
    `  version     = EXCLUDED.version,`,
    `  tags        = EXCLUDED.tags,`,
    `  content     = EXCLUDED.content,`,
    `  updated_at  = now();`,
    '',
  );
}
lines.push(`-- Seeded ${skillNames.length} skill(s): ${skillNames.join(', ')}`);
process.stdout.write(lines.join('\n'));
