#!/usr/bin/env node
/**
 * auto-test-cycle — scheduled health check for the whole system.
 *
 * WHY THIS EXISTS
 * The gate answers "does everything pass right now". It does not answer the
 * question that actually matters between sessions: **what changed since last
 * time.** A suite that has failed for months reads identically to one that
 * broke an hour ago, and that is precisely how this repo ended up with 127
 * unchained suites and a `smoke:all` chain silently halting at suite 148.
 *
 * So this stores a baseline and reports DELTAS:
 *   - newly failing suites            → a real regression, exit non-zero
 *   - newly passing suites            → someone fixed something, worth knowing
 *   - production invariants that flipped PASS→WARN/FAIL
 *   - typecheck error-count movement, attributed per file
 *
 * A suite that was already failing is reported as "known" and does NOT fail the
 * cycle — otherwise a single long-standing failure makes the alarm useless and
 * everyone learns to ignore it.
 *
 * Usage:
 *   node scripts/auto-test-cycle.mjs                 # full cycle
 *   node scripts/auto-test-cycle.mjs --no-prod       # skip live DB checks
 *   node scripts/auto-test-cycle.mjs --invariants-only # refresh live read-only evidence only
 *   node scripts/auto-test-cycle.mjs --update-baseline
 *
 * Exit: 0 = no regression, 1 = regression, 2 = harness error.
 */

import { execFile } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { promisify } from 'node:util';
import { readFileSync, writeFileSync, mkdirSync, existsSync, renameSync, unlinkSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const run = promisify(execFile);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPORT_DIR = join(ROOT, 'ops-records', 'auto-test');
const BASELINE = join(REPORT_DIR, 'baseline.json');

const argv = process.argv.slice(2);
const skipProd = argv.includes('--no-prod');
const invariantsOnly = argv.includes('--invariants-only');
const updateBaseline = argv.includes('--update-baseline');

const stamp = new Date().toISOString();
const cycleRunId = randomUUID();
const log = (...a) => console.log(...a);

export const AUTO_TEST_REPORT_SCHEMA_VERSION = 2;

function writeJsonAtomically(path, value) {
  const tempPath = `${path}.${process.pid}.${randomUUID()}.tmp`;
  try {
    writeFileSync(tempPath, `${JSON.stringify(value, null, 2)}\n`, { encoding: 'utf8', mode: 0o644 });
    renameSync(tempPath, path);
  } finally {
    try { unlinkSync(tempPath); } catch { /* renamed successfully or never created */ }
  }
}

function isCurrentTimestamp(value, notBefore) {
  const parsed = Date.parse(String(value ?? ''));
  const floor = Date.parse(String(notBefore ?? ''));
  return Number.isFinite(parsed) && Number.isFinite(floor) && parsed >= floor;
}

/** Reject stale, malformed, or mismatched child evidence before publication. */
export function validateInvariantReport(report, expectedRunId, notBefore) {
  if (!report || typeof report !== 'object' || Array.isArray(report)) {
    throw new Error('Invariant report is not an object.');
  }
  if (report.schemaVersion !== 2) throw new Error('Invariant report schema is not current.');
  if (report.runId !== expectedRunId) throw new Error('Invariant report runId does not match this cycle.');
  if (!isCurrentTimestamp(report.generatedAt, notBefore)) {
    throw new Error('Invariant report was not generated by this cycle.');
  }
  if (!['complete', 'harness_error'].includes(report.status)) {
    throw new Error(`Invariant report status is invalid: ${String(report.status)}`);
  }
  if (!Array.isArray(report.results)) throw new Error('Invariant report results are missing.');
  if (report.status === 'harness_error') {
    if (report.results.length !== 0) throw new Error('Harness-error reports cannot publish partial results.');
    return report;
  }

  const names = new Set();
  for (const result of report.results) {
    if (!result || typeof result !== 'object') throw new Error('Invariant result is malformed.');
    if (!['PASS', 'WARN', 'FAIL'].includes(result.level)) {
      throw new Error(`Invariant level is invalid: ${String(result.level)}`);
    }
    if (typeof result.name !== 'string' || !result.name.trim() || names.has(result.name)) {
      throw new Error('Invariant result names must be non-empty and unique.');
    }
    names.add(result.name);
  }
  return report;
}

function harnessErrorInvariantReport(runId, startedAt, code) {
  return {
    schemaVersion: 2,
    runId,
    status: 'harness_error',
    startedAt,
    generatedAt: new Date().toISOString(),
    error: {
      code,
      message: 'Production invariant checks did not complete. See the scheduler log for details.',
    },
    results: [],
  };
}

async function sh(cmd, args, opts = {}) {
  try {
    const { stdout } = await run(cmd, args, { cwd: ROOT, maxBuffer: 64 * 1024 * 1024, timeout: opts.timeout ?? 1_800_000 });
    return { ok: true, stdout };
  } catch (e) {
    // Non-zero exit is expected (a failing gate); keep the output either way.
    return {
      ok: false,
      stdout: (e?.stdout ?? '') + (e?.stderr ?? ''),
      error: e?.message,
      exitCode: typeof e?.code === 'number' ? e.code : null,
    };
  }
}

/** tsc emits `path(line,col): error TSxxxx: msg` — count per file. */
function typecheckByFile(out) {
  const byFile = {};
  for (const m of out.matchAll(/^(.+?)\(\d+,\d+\):\s+error TS/gm)) {
    const f = m[1].trim();
    byFile[f] = (byFile[f] ?? 0) + 1;
  }
  return byFile;
}

async function collect() {
  const result = {
    schemaVersion: AUTO_TEST_REPORT_SCHEMA_VERSION,
    runId: cycleRunId,
    stamp,
    status: 'running',
    scope: invariantsOnly ? 'invariants-only' : skipProd ? 'local-only' : 'full',
    typecheck: null,
    suites: null,
    invariants: null,
    invariantRun: null,
  };

  if (invariantsOnly) {
    result.typecheck = { status: 'skipped', total: null, byFile: {} };
    result.suites = { status: 'skipped', total: null, failing: [] };
  } else {
    log('· typecheck…');
    const tc = await sh('npm', ['run', 'typecheck']);
    const byFile = typecheckByFile(tc.stdout);
    const errorCount = Object.values(byFile).reduce((a, b) => a + b, 0);
    result.typecheck = {
      status: !tc.ok && errorCount === 0 ? 'harness_error' : 'complete',
      total: !tc.ok && errorCount === 0 ? null : errorCount,
      byFile,
      ...(!tc.ok && errorCount === 0
        ? { error: 'Typecheck did not produce TypeScript diagnostics. See the scheduler log for details.' }
        : {}),
    };
    if (result.typecheck.status === 'harness_error') log('  ! typecheck harness did not complete');
    else log(`  ${result.typecheck.total} errors across ${Object.keys(byFile).length} files`);

    log('· smoke suites…');
    const jsonPath = join(REPORT_DIR, 'last-smoke.json');
    const smokeStartedAt = new Date().toISOString();
    await sh('node', ['scripts/run-smokes.mjs', '--timeout', '180s', '--json', jsonPath]);
    try {
      const d = JSON.parse(readFileSync(jsonPath, 'utf8'));
      if (!isCurrentTimestamp(d.generatedAt, smokeStartedAt)) {
        throw new Error('smoke report was not generated by this cycle');
      }
      const list = d.suites ?? d.results;
      if (!Array.isArray(list)) throw new Error('smoke report results are missing');
      const failing = list
        .filter((s) => !['pass', 'passed', 'ok'].includes(String(s.status ?? '').toLowerCase()))
        .map((s) => s.name)
        .sort();
      result.suites = { status: 'complete', generatedAt: d.generatedAt, total: list.length, failing };
      log(`  ${list.length} suites, ${failing.length} failing`);
    } catch (e) {
      result.suites = {
        status: 'harness_error',
        total: null,
        failing: [],
        error: 'Smoke checks did not produce a current report. See the scheduler log for details.',
      };
      log(`  ! could not read a current smoke report (${e?.message ?? e})`);
    }
  }

  if (!skipProd) {
    log('· production invariants…');
    const invPath = join(REPORT_DIR, 'last-invariants.json');
    const invariantRunId = randomUUID();
    const invariantStartedAt = new Date().toISOString();
    // Invalidate the previous record before launch. If the child is killed,
    // readers see `running` for this exact run rather than old health levels.
    writeJsonAtomically(invPath, {
      schemaVersion: 2,
      runId: invariantRunId,
      status: 'running',
      startedAt: invariantStartedAt,
      generatedAt: invariantStartedAt,
      results: [],
    });
    await sh('node', [
      'scripts/memory-prod-invariants.mjs', '--json', invPath, '--run-id', invariantRunId,
    ]);
    try {
      const d = validateInvariantReport(
        JSON.parse(readFileSync(invPath, 'utf8')),
        invariantRunId,
        invariantStartedAt,
      );
      if (d.status === 'harness_error') {
        result.invariantRun = {
          status: 'harness_error',
          runId: invariantRunId,
          generatedAt: d.generatedAt,
          errorCode: d.error?.code ?? 'production_invariant_harness_failed',
        };
        log('  ! production invariant harness did not complete');
      } else {
        result.invariants = Object.fromEntries(d.results.map((r) => [r.name, r.level]));
        result.invariantRun = {
          status: 'complete',
          runId: invariantRunId,
          generatedAt: d.generatedAt,
        };
      }
      if (result.invariants) {
        const bad = Object.values(result.invariants).filter((l) => l !== 'PASS').length;
        log(`  ${Object.keys(result.invariants).length} invariants, ${bad} not-PASS`);
      }
    } catch (e) {
      const errorReport = harnessErrorInvariantReport(
        invariantRunId,
        invariantStartedAt,
        'invariant_report_contract_invalid',
      );
      writeJsonAtomically(invPath, errorReport);
      result.invariants = null;
      result.invariantRun = {
        status: 'harness_error',
        runId: invariantRunId,
        generatedAt: errorReport.generatedAt,
        errorCode: errorReport.error.code,
      };
      log(`  ! could not read a current invariant report (${e?.message ?? e})`);
    }
  } else {
    result.invariantRun = { status: 'skipped', reason: 'no-prod' };
  }
  return result;
}

/**
 * Re-run newly-failing suites ONE AT A TIME before calling them regressions.
 *
 * The concurrent runner spawns many `npx tsx` processes, and under load tsx's
 * module loader can return `undefined` from its `load` hook
 * (ERR_INVALID_RETURN_PROPERTY_VALUE) — the suite "fails" without its code ever
 * running. The very first scheduled cycle hit exactly this and reported
 * `smoke:tool-result-formatters` as a regression; it passed 3/3 in isolation.
 *
 * A detector that cries wolf gets ignored, which is the same outcome as having
 * no detector. So a newly-failing suite is only a regression if it fails again
 * on a serial re-run; otherwise it is recorded as flaky — visible, but it does
 * not trip the alarm.
 */
async function confirmFailures(names) {
  const confirmed = [];
  const flaky = [];
  for (const name of names) {
    const r = await sh('npm', ['run', name], { timeout: 300_000 });
    (r.ok ? flaky : confirmed).push(name);
  }
  return { confirmed, flaky };
}

function laneIsComplete(lane) {
  return lane && (lane.status === undefined || lane.status === 'complete');
}

export function diff(base, now) {
  const out = { regressions: [], improvements: [], known: [] };
  if (now.typecheck?.status === 'harness_error') {
    out.regressions.push('typecheck harness unavailable: no current typecheck evidence');
  }
  if (now.suites?.status === 'harness_error') {
    out.regressions.push('smoke harness unavailable: no current suite evidence');
  }
  if (now.invariantRun?.status === 'harness_error') {
    out.regressions.push('production invariant harness unavailable: no current production evidence');
  }
  if (!base) return out;

  if (laneIsComplete(now.suites)) {
    const wasFailing = new Set(base.suites?.failing ?? []);
    const isFailing = new Set(now.suites?.failing ?? []);
    for (const s of isFailing) (wasFailing.has(s) ? out.known : out.regressions).push(`suite newly failing: ${s}`);
    for (const s of wasFailing) if (!isFailing.has(s)) out.improvements.push(`suite now passing: ${s}`);
  }

  // Typecheck: attribute movement per file so another session's churn in their
  // own files is never reported as this work regressing.
  if (laneIsComplete(now.typecheck)) {
    const bf = base.typecheck?.byFile ?? {};
    const nf = now.typecheck?.byFile ?? {};
    for (const [f, n] of Object.entries(nf)) {
      const was = bf[f] ?? 0;
      if (n > was) out.regressions.push(`typecheck: ${f} ${was} → ${n} errors`);
    }
    for (const [f, was] of Object.entries(bf)) {
      const n = nf[f] ?? 0;
      if (n < was) out.improvements.push(`typecheck: ${f} ${was} → ${n} errors`);
    }
  }

  if (now.invariantRun?.status === 'complete' || (!now.invariantRun && now.invariants)) {
    const bi = base.invariants ?? {};
    const ni = now.invariants ?? {};
    const rank = { PASS: 0, WARN: 1, FAIL: 2 };
    for (const [name, level] of Object.entries(ni)) {
      const was = bi[name];
      if (was && (rank[level] ?? 0) > (rank[was] ?? 0)) out.regressions.push(`invariant ${was}→${level}: ${name}`);
      if (was && (rank[level] ?? 0) < (rank[was] ?? 0)) out.improvements.push(`invariant ${was}→${level}: ${name}`);
    }
  }
  return out;
}

async function main() {
  mkdirSync(REPORT_DIR, { recursive: true });
  log(`auto-test-cycle  ${stamp}\n`);

  // Publish an explicit in-progress record before any long-running work. A
  // killed scheduler therefore cannot leave an older completed report looking
  // like the result of the current attempt.
  writeJsonAtomically(join(REPORT_DIR, 'latest.json'), {
    schemaVersion: AUTO_TEST_REPORT_SCHEMA_VERSION,
    runId: cycleRunId,
    stamp,
    status: 'running',
    scope: invariantsOnly ? 'invariants-only' : skipProd ? 'local-only' : 'full',
  });

  const now = await collect();
  const base = existsSync(BASELINE) ? JSON.parse(readFileSync(BASELINE, 'utf8')) : null;
  const d = diff(base, now);

  // Confirm-before-alarm (see confirmFailures).
  const newlyFailing = d.regressions
    .filter((r) => r.startsWith('suite newly failing: '))
    .map((r) => r.replace('suite newly failing: ', ''));
  if (newlyFailing.length) {
    log(`\n· re-verifying ${newlyFailing.length} newly-failing suite(s) serially…`);
    const { confirmed, flaky } = await confirmFailures(newlyFailing);
    d.flaky = flaky;
    for (const f of flaky) log(`  ~ flaky (passed on re-run): ${f}`);
    // Drop unconfirmed ones from the regression list, and from the recorded
    // failing set so the baseline does not memorialise a flake as "known".
    d.regressions = d.regressions.filter(
      (r) => !r.startsWith('suite newly failing: ') || confirmed.includes(r.replace('suite newly failing: ', '')),
    );
    if (now.suites?.failing) {
      now.suites.failing = now.suites.failing.filter((n) => !flaky.includes(n));
    }
  }

  const hasHarnessError = now.typecheck?.status === 'harness_error'
    || now.suites?.status === 'harness_error'
    || now.invariantRun?.status === 'harness_error';
  now.status = hasHarnessError ? 'harness_error' : d.regressions.length ? 'regression' : 'complete';
  now.completedAt = new Date().toISOString();
  writeJsonAtomically(join(REPORT_DIR, 'latest.json'), { ...now, diff: d });

  log('\n─── delta vs baseline ───');
  if (!base) {
    log('  no baseline yet — writing one. Next run reports deltas.');
  } else {
    for (const r of d.regressions) log(`  ✗ REGRESSION  ${r}`);
    for (const i of d.improvements) log(`  ✓ improved    ${i}`);
    if (d.known.length) log(`  · ${d.known.length} known failure(s) carried over (not a regression)`);
    if (!d.regressions.length && !d.improvements.length) log('  no change');
  }

  const fullEvidence = !skipProd
    && !invariantsOnly
    && laneIsComplete(now.typecheck)
    && laneIsComplete(now.suites)
    && now.invariantRun?.status === 'complete';
  if (fullEvidence && (!base || updateBaseline || d.regressions.length === 0)) {
    writeJsonAtomically(BASELINE, now);
    log(`\nbaseline updated → ${BASELINE.replace(ROOT + '/', '')}`);
  } else if (!fullEvidence) {
    log('\nbaseline NOT updated (this run did not produce all three evidence lanes).');
  } else {
    log('\nbaseline NOT updated (regressions present) — fix, or re-run with --update-baseline to accept.');
  }

  process.exit(hasHarnessError ? 2 : d.regressions.length ? 1 : 0);
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  main().catch((e) => {
    console.error('harness error:', e?.message ?? e);
    try {
      writeJsonAtomically(join(REPORT_DIR, 'latest.json'), {
        schemaVersion: AUTO_TEST_REPORT_SCHEMA_VERSION,
        runId: cycleRunId,
        stamp,
        completedAt: new Date().toISOString(),
        status: 'harness_error',
        scope: invariantsOnly ? 'invariants-only' : skipProd ? 'local-only' : 'full',
        error: 'Auto-test cycle did not complete. See the scheduler log for details.',
      });
    } catch (writeError) {
      console.error('could not write harness-error report:', writeError?.message ?? writeError);
    }
    process.exitCode = 2;
  });
}
