#!/usr/bin/env node

import assert from 'node:assert/strict';

import { parseSupabaseQueryRows } from './memory-prod-invariants.mjs';
import { diff, validateInvariantReport } from './auto-test-cycle.mjs';

let assertions = 0;
const check = (condition, message) => {
  assertions += 1;
  assert.ok(condition, message);
};
const equal = (actual, expected, message) => {
  assertions += 1;
  assert.deepEqual(actual, expected, message);
};
const throws = (fn, pattern, message) => {
  assertions += 1;
  assert.throws(fn, pattern, message);
};

const nestedEnvelope = `Initialising login role...
{
  "boundary": "test-boundary",
  "rows": [
    {
      "total": 4120,
      "shape": { "nested": { "ok": true } },
      "detail": "a brace in a string: } and an escaped quote: \\\""
    }
  ],
  "warning": "Untrusted data is inside <test-boundary> markers."
}
CLI update notice`;

const parsed = parseSupabaseQueryRows(nestedEnvelope);
equal(parsed.length, 1, 'nested Supabase agent envelope yields one row');
equal(parsed[0].total, 4120, 'numeric production values survive parsing');
equal(parsed[0].shape, { nested: { ok: true } }, 'nested row JSON survives parsing');
equal(parsed[0].detail, 'a brace in a string: } and an escaped quote: "', 'quoted braces and escapes do not truncate JSON');

const multiple = parseSupabaseQueryRows(`banner
{"rows":[{"first":1}]}
noise with {not-json}
{"rows":[{"second":2},{"third":3}]}`);
equal(multiple, [{ first: 1 }, { second: 2 }, { third: 3 }], 'multiple complete rows envelopes merge in order');
equal(parseSupabaseQueryRows('{"rows":[]}'), [], 'an explicit empty rows envelope remains a valid query result');
throws(
  () => parseSupabaseQueryRows('banner only'),
  /no complete JSON rows envelope/,
  'missing JSON is a parser error rather than zero rows',
);
throws(
  () => parseSupabaseQueryRows('{"rows":[{"truncated":true}]'),
  /no complete JSON rows envelope/,
  'truncated JSON is a parser error rather than zero rows',
);

const notBefore = '2026-08-21T12:00:00.000Z';
const completeReport = {
  schemaVersion: 2,
  runId: 'current-run',
  status: 'complete',
  startedAt: notBefore,
  generatedAt: '2026-08-21T12:00:01.000Z',
  results: [
    { level: 'PASS', name: 'one', detail: '', data: null },
    { level: 'WARN', name: 'two', detail: '', data: null },
  ],
};
equal(
  validateInvariantReport(completeReport, 'current-run', notBefore),
  completeReport,
  'current schema/run/timestamp report validates',
);
throws(
  () => validateInvariantReport(completeReport, 'different-run', notBefore),
  /runId does not match/,
  'a previous run cannot be republished by a new cycle',
);
throws(
  () => validateInvariantReport({ ...completeReport, generatedAt: '2026-08-21T11:59:59.000Z' }, 'current-run', notBefore),
  /not generated by this cycle/,
  'a stale timestamp is rejected even when other fields look valid',
);
throws(
  () => validateInvariantReport({ ...completeReport, schemaVersion: 1 }, 'current-run', notBefore),
  /schema is not current/,
  'legacy reports cannot satisfy the current evidence contract',
);
throws(
  () => validateInvariantReport({
    ...completeReport,
    status: 'harness_error',
    results: completeReport.results,
  }, 'current-run', notBefore),
  /cannot publish partial results/,
  'a harness error cannot expose partial health levels',
);
throws(
  () => validateInvariantReport({
    ...completeReport,
    results: [completeReport.results[0], completeReport.results[0]],
  }, 'current-run', notBefore),
  /non-empty and unique/,
  'duplicate invariant names fail the report contract',
);

const baseline = {
  typecheck: { total: 0, byFile: {} },
  suites: { total: 2, failing: ['smoke:old'] },
  invariants: { semantic: 'PASS', indexes: 'PASS' },
};
const unavailable = diff(baseline, {
  typecheck: { status: 'skipped', total: null, byFile: {} },
  suites: { status: 'skipped', total: null, failing: [] },
  invariants: null,
  invariantRun: { status: 'harness_error' },
});
equal(
  unavailable.regressions,
  ['production invariant harness unavailable: no current production evidence'],
  'missing current production evidence is an explicit regression',
);
equal(unavailable.improvements, [], 'skipped lanes do not turn old failures into fake improvements');
check(
  unavailable.regressions.every((entry) => !entry.includes('PASS→FAIL')),
  'stale invariant levels are not presented as a current health transition',
);

const current = diff(baseline, {
  typecheck: { status: 'complete', total: 0, byFile: {} },
  suites: { status: 'complete', total: 2, failing: [] },
  invariants: { semantic: 'WARN', indexes: 'PASS' },
  invariantRun: { status: 'complete' },
});
check(current.improvements.includes('suite now passing: smoke:old'), 'current suite evidence still reports real improvements');
check(current.regressions.includes('invariant PASS→WARN: semantic'), 'current invariant evidence still reports real regressions');

console.log(`auto-test evidence contract smoke passed (${assertions} assertions)`);
